"""Bind signed images and runtime receipts to the reviewed sources that determine them, not the whole commit."""

import argparse
import fnmatch
import hashlib
import json
from pathlib import Path
import re
import subprocess

from scripts.customer_migration import ROOT, MigrationError, require


SCHEMA = "llmgw-runtime-revision/v1"
ANNOTATION = "llmgw.runtimeRevision"
# Git inputs per signed runtime (the llmgw.runtime annotation). Everything COPY'd into the image is listed, plus the
# files that define the contract the image and its receipts are accepted under; docs, IaC, renderers and stage code
# are excluded, so they no longer force a rebuild. Paths are matched against the Git tree, never the working copy.
RUNTIME_INPUTS = {
    # LiteLLM/runtime/** is the whole COPY source: Dockerfile (pinned base digest and checksummed wheels), its BuildKit
    # ignore file, hash-locked security-requirements.txt and every module under /opt/llmgw (application, callbacks,
    # Codex passthrough, Azure PostgreSQL and the Prisma schema migrator). source_supply_chain.py holds the build
    # command and RUNTIME_CONTRACT the image must satisfy; schema_runtime.py runs the in-image migrator whose result
    # the Stage5 schema receipt attests.
    "azure": {"trees": ("LiteLLM/runtime",), "files": ("scripts/source_supply_chain.py", "scripts/schema_runtime.py")},
    # auth-proxy/ build context: Dockerfile (pinned Node digest), .dockerignore, npm manifest and lockfile, the
    # top-level *.mjs modules and the native UI route list; test/, entra/ and README_ZH.md are never copied.
    "auth-proxy": {"files": ("auth-proxy/Dockerfile", "auth-proxy/.dockerignore", "auth-proxy/package.json", "auth-proxy/package-lock.json", "auth-proxy/native-ui-routes.json"), "globs": (("auth-proxy", "*.mjs"),)},
    # The collector is imported, not built: only the reviewed upstream digest determines it.
    "collector": {"files": ("scripts/collector_image.py",)},
}


def selected(runtime, path):
    inputs = RUNTIME_INPUTS[runtime]
    if path in inputs.get("files", ()):
        return True
    parent, _, name = path.rpartition("/")
    if any(parent == directory and fnmatch.fnmatchcase(name, pattern) for directory, pattern in inputs.get("globs", ())):
        return True
    # Bytecode is excluded by the runtime Dockerfile.dockerignore and regenerated by Python; every other file counts.
    return any(path.startswith(tree + "/") for tree in inputs.get("trees", ())) and "__pycache__" not in path.split("/") and not name.endswith((".pyc", ".pyo"))


def roots(runtime):
    inputs = RUNTIME_INPUTS[runtime]
    return sorted({*inputs.get("trees", ()), *inputs.get("files", ()), *(directory for directory, _ in inputs.get("globs", ()))})


def git(arguments, root, run):
    try:
        result = run(["git", "-C", str(root), *arguments], capture_output=True, text=True, check=False, timeout=60)
    except (OSError, subprocess.SubprocessError):
        raise MigrationError("Git is required to compute the runtime revision") from None
    require(result.returncode == 0, "Unable to read the reviewed Git tree for the runtime revision")
    return result.stdout


def runtime_inputs(runtime, revision, root=ROOT, run=subprocess.run):
    require(runtime in RUNTIME_INPUTS, "Unknown runtime revision kind")
    require(isinstance(revision, str) and re.fullmatch(r"[0-9a-f]{40}", revision) is not None, "A full source revision is required")
    entries = []
    for record in git(["ls-tree", "-r", "-z", "--full-tree", revision, "--", *roots(runtime)], root, run).split("\0"):
        if not record:
            continue
        metadata, _, path = record.partition("\t")
        mode, kind, blob = metadata.split(" ")
        if not selected(runtime, path):
            continue
        # A submodule or other non-blob would be copied by docker build but cannot be hashed from Git here.
        require(kind == "blob" and re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", blob) is not None and mode in {"100644", "100755", "120000"}, "Unexpected Git object in runtime inputs")
        entries.append([path, mode, blob])
    entries.sort()
    paths = {entry[0] for entry in entries}
    inputs = RUNTIME_INPUTS[runtime]
    require(set(inputs.get("files", ())) <= paths and all(any(path.startswith(tree + "/") for path in paths) for tree in inputs.get("trees", ())), "Reviewed revision lacks required runtime inputs")
    return entries


def runtime_revision(runtime, revision, root=ROOT, run=subprocess.run):
    document = {"schema": SCHEMA, "runtime": runtime, "inputs": runtime_inputs(runtime, revision, root, run)}
    return hashlib.sha256(json.dumps(document, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def require_clean(runtime, revision, root=ROOT, run=subprocess.run):
    require(git(["rev-parse", "HEAD"], root, run).strip() == revision, "Build the image from a checkout of the reviewed revision")
    inputs = RUNTIME_INPUTS[runtime]
    # Glob pathspecs keep ignored dependency trees (node_modules) out of the scan; selected() still decides.
    pathspecs = [*inputs.get("trees", ()), *inputs.get("files", ()), *(f":(glob){directory}/{pattern}" for directory, pattern in inputs.get("globs", ()))]
    records = git(["status", "--porcelain=v1", "-z", "--untracked-files=all", "--ignored", "--", *pathspecs], root, run).split("\0")
    changed, index = [], 0
    while index < len(records):
        record = records[index]
        index += 1
        if not record:
            continue
        changed.append(record[3:])
        if record[0] in "RC":
            changed.append(records[index])
            index += 1
    # Ignored and untracked files count too (listed per file with --untracked-files=all): docker build reads the
    # working tree, not Git, so anything the Dockerfile would COPY must equal the reviewed blob.
    dirty = sorted({path for path in changed if selected(runtime, path)})
    require(not dirty, f"Commit or remove local changes to {runtime} image inputs before building: " + ", ".join(dirty[:5]))


def build_runtime_revision(runtime, revision, root=ROOT, run=subprocess.run):
    """Runtime revision for an image built or imported from this checkout; refuses inputs that differ from Git."""
    require_clean(runtime, revision, root, run)
    return runtime_revision(runtime, revision, root, run)


def receipt_current(receipt, revision, current):
    """New receipts bind the runtime revision; receipts written before it existed still need the exact commit."""
    if "runtimeRevision" in receipt:
        return receipt["runtimeRevision"] == current
    return receipt.get("revision") == revision


def signature_binding(signatures, image, runtime, environment, revision, current):
    """Return how a verified Cosign payload binds the image to the reviewed sources, or None."""
    require(isinstance(signatures, list), "Cosign verification returned an unexpected payload")
    digest = image.rsplit("@", 1)[-1]
    legacy = False
    for item in signatures:
        if not isinstance(item, dict) or item.get("critical", {}).get("image", {}).get("docker-manifest-digest") != digest:
            continue
        optional = item.get("optional") or {}
        if optional.get("llmgw.runtime") != runtime or optional.get("llmgw.environment") != environment:
            continue
        if ANNOTATION in optional:
            if optional[ANNOTATION] == current:
                return "runtimeRevision"
        elif optional.get("llmgw.revision") == revision:
            legacy = True
    return "revision" if legacy else None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runtime", choices=sorted(RUNTIME_INPUTS), required=True)
    parser.add_argument("--revision", help="Reviewed commit; defaults to HEAD")
    parser.add_argument("--require-clean", action="store_true", help="Refuse when the working tree differs from Git in the runtime inputs")
    parser.add_argument("--list", action="store_true", help="Print the hashed inputs instead of the digest")
    args = parser.parse_args()
    revision = args.revision or git(["rev-parse", "HEAD"], ROOT, subprocess.run).strip()
    if args.list:
        for path, mode, blob in runtime_inputs(args.runtime, revision):
            print(mode, blob, path)
        return 0
    print(build_runtime_revision(args.runtime, revision) if args.require_clean else runtime_revision(args.runtime, revision))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except MigrationError as error:
        raise SystemExit(str(error)) from None
